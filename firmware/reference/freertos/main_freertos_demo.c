static void prvLEDTask(void *pvParameters)
{
  LEDBlinkInfo_TypeDef *info = (LEDBlinkInfo_TypeDef *)pvParameters;

  for(;;)
  {
    HAL_GPIO_WritePin(info->LED_GPIOx, info->LED_Pin,GPIO_PIN_SET);
    vTaskDelay(pdMS_TO_TICKS(info->Period / 2));
    HAL_GPIO_WritePin(info->LED_GPIOx, info->LED_Pin,GPIO_PIN_RESET);
    vTaskDelay(pdMS_TO_TICKS(info->Period / 2));
  }
}

static void prvTask1(void *pvParameters)
{
	vTaskDelay(pdMS_TO_TICKS(1000));

	vTaskSuspend(xLED1TaskHandle);
	vTaskDelay(pdMS_TO_TICKS(1000));

	vTaskResume(xLED1TaskHandle);
	vTaskDelay(pdMS_TO_TICKS(1000));

	vTaskDelete(xLED1TaskHandle);

	vTaskDelete(NULL);
}
