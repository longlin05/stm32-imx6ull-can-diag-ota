/* 水平偏移：个别模块第 0 列不对齐时才需要（这里是 0，不用开） */
//#define SSD1306_X_OFFSET

/* --------------------------------------------------------------------------
 * 字体裁剪：只编真正用到的，其余数组不参与编译（见 ssd1306_fonts.c 的 #ifdef）
 * 7x10  = 小字，标题和状态行（128px 宽能放 18 个字符）
 * 11x18 = 大字，温湿度数值（128px 宽能放 11 个字符）
 * ------------------------------------------------------------------------*/
